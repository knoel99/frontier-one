#!/usr/bin/env python3
"""Fill config/prices.toml with the list price of every model of config/providers.toml.

Source: the public OpenRouter model list (https://openrouter.ai/api/v1/models, no key needed), whose prices are
the providers' list prices in USD per token. Each model id is matched to an OpenRouter id (provider prefix, version
dots: claude-fable-5-2 -> anthropic/claude-fable-5.2). Entries marked `manual = true` in prices.toml are kept as they
are (prices read on a provider's own page). Models without a match are reported: the budget then counts them at the
highest price of their provider and says so.
"""

from __future__ import annotations

import datetime as dt
import json
import pathlib
import re
import sys
import tomllib
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
PRICES = ROOT / "config" / "prices.toml"
PREFIX = {"openai": "openai", "anthropic": "anthropic", "google": "google", "xai": "x-ai", "mistral": "mistralai",
          "deepseek": "deepseek", "moonshot": "moonshotai", "alibaba": "qwen", "zhipu": "z-ai"}
# cerebras serves other labs' open models at its own price: its entries are `manual` (read on its endpoints)
# Our id -> OpenRouter id, where the names differ beyond version dots.
ALIASES = {"deepseek-flash": "deepseek/deepseek-v4.1-flash-1017", "mistral-large-4": "mistralai/mistral-large-4-0",
           "mistral-medium-3.5": "mistralai/mistral-medium-3-5"}


def candidates(provider: str, model: str) -> list[str]:
    pre = PREFIX.get(provider, provider)
    dotted = re.sub(r"(?<=\d)-(?=\d)", ".", model)
    out = [f"{pre}/{model}", f"{pre}/{dotted}"]
    if model in ALIASES:
        out.insert(0, ALIASES[model])
    return out


def per_million(x) -> float | None:
    try:
        return round(float(x) * 1e6, 6) if x not in (None, "", "-1") else None
    except (TypeError, ValueError):
        return None


def main() -> int:
    with open(ROOT / "config" / "providers.toml", "rb") as f:
        providers = tomllib.load(f)["providers"]
    old = tomllib.loads(PRICES.read_text()) if PRICES.exists() else {}
    req = urllib.request.Request("https://openrouter.ai/api/v1/models", headers={"User-Agent": "frontier-prices"})
    with urllib.request.urlopen(req, timeout=60) as r:
        catalog = {m["id"]: m for m in json.load(r)["data"]}
    today = dt.date.today().isoformat()
    lines = ["# List prices in USD per million tokens, used by the budget (frontier/budget.py).",
             "# Generated by tools/update_prices.py from https://openrouter.ai/api/v1/models; entries with",
             "# manual = true were read on the provider's own pricing page and are kept as they are (the provider's",
             "# own price is what a direct API call costs; OpenRouter may list a third-party host for open-weight models).",
             "# offpeak_x applies outside the peak_utc windows (weekdays, UTC).",
             "# A speed mode multiplies these prices by its price_x (config/providers.toml).", ""]
    missing = []
    for provider, p in providers.items():
        variants = [v for m in p.get("modes", {}).values() for v in m.get("model", {}).values()]
        for model in dict.fromkeys([*p["tiers"].values(), *variants]):
            prev = old.get("models", {}).get(model, {})
            if prev.get("manual"):
                entry = prev
            else:
                hit = next((catalog[c] for c in candidates(provider, model) if c in catalog), None)
                if hit is None:
                    missing.append(f"{provider}/{model}")
                    if prev:
                        entry = prev
                    else:
                        continue
                else:
                    pr = hit["pricing"]
                    entry = {"input": per_million(pr.get("prompt")), "output": per_million(pr.get("completion")),
                             "cache_read": per_million(pr.get("input_cache_read")),
                             "cache_write": per_million(pr.get("input_cache_write")),
                             "source": f"openrouter:{hit['id']}", "date": today}
            lines.append(f'[models."{model}"]')
            entry = {"provider": provider, **{k: v for k, v in entry.items() if k != "provider"}}
            for k, v in entry.items():
                if v is not None:
                    lines.append(f"{k} = {json.dumps(v)}")
            lines.append("")
    PRICES.write_text("\n".join(lines))
    print(f"wrote {PRICES.relative_to(ROOT)}")
    if missing:
        print("no OpenRouter price for: " + ", ".join(missing) + " (add a manual entry)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
